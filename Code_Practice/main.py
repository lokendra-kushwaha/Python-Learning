# Calculation on two numbers using arithmetic operators
x = 10
y = 6
print(x, "+", y, "=", x + y)
print(x, "-", y, "=", x - y)
print(x, "x", y, "=", x * y)
print(x, "/", y, "=", x / y)
print(x, "//", y, "=", x // y, "(Floor Division)")
print(x, "%", y, "=", x % y, "(Modulus)")